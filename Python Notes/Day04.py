# Set

# A set stores unique values.

numbers = {10, 20, 30, 20, 10}
print(numbers)

# Dictionary

# A dictionary stores data in key-value pairs.

student = {
    "name": "Raj",
    "age": 22,
    "course": "Python Full Stack"
}

print(student)
print(student["name"])
print(student["course"])

# Type Casting

# Converting one data type into another:

num = "100"
print(type(num))
num = int(num)
print(type(num))
print(num + 50)