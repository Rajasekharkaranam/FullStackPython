# Arithmetic Operators
a = 10
b = 3
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a ** b)
print(a // b)

#Comparison Operators
a = 10
b = 20
print(a == b)
print(a != b)
print(a > b)
print(a < b)

# Logical Operators
age = 22
has_id = True

print(age >= 18 and has_id)
print(age >= 18 or has_id)
print(not has_id)